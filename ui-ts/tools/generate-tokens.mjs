import { themeFromSourceColor, argbFromHex, hexFromArgb } from '@material/material-color-utilities';
import { writeFileSync } from 'node:fs';
const theme = themeFromSourceColor(argbFromHex('#5266a4'));
const scheme = (dark) => {
  const roles = theme.schemes[dark ? 'dark' : 'light'].toJSON();
  const tones = dark ? [6,4,10,12,17,22] : [98,100,96,94,92,90];
  ['surface-dim','surface-container-lowest','surface-container-low','surface-container','surface-container-high','surface-container-highest'].forEach((name,index) => { roles[name] = theme.palettes.neutral.tone(tones[index]); });
  return Object.entries(roles).map(([key,value]) => `  --md-${key.replace(/[A-Z]/g, s => '-'+s.toLowerCase())}: ${hexFromArgb(value)};`).join('\n');
};
const aliases = `  --bg-0: var(--md-surface); --bg-1: var(--md-surface-container-low);
  --bg-2: var(--md-surface-container-lowest); --bg-3: var(--md-surface-container-high); --bg-4: var(--md-surface-container-highest);
  --text-1: var(--md-on-surface); --text-2: var(--md-on-surface-variant); --text-3: var(--md-outline);
  --stroke-1: var(--md-outline-variant); --stroke-2: var(--md-outline);
  --accent: var(--md-primary); --accent-strong: var(--md-primary); --accent-dim: var(--md-primary-container);
  --danger: var(--md-error); --danger-strong: var(--md-error); --danger-dim: var(--md-error-container);
  --ok: var(--md-primary); --ok-dim: var(--md-primary-container); --warn: var(--md-tertiary); --warn-dim: var(--md-tertiary-container);
  --v-qualcomm: var(--md-primary); --v-crash: var(--md-tertiary); --v-samsung: var(--md-primary);
  --v-lg: var(--md-primary); --v-mtk: var(--md-primary); --v-spd: var(--md-primary);
  --sans: 'Roboto', sans-serif; --mono: 'JetBrains Mono', monospace;
  --r-full: 999px; --r-sm: 8px; --r-md: 12px; --r-lg: 16px; --r-xl: 28px;
  --scrim: rgba(0,0,0,.5); --shadow-1: 0 1px 3px #0002; --shadow-2: 0 3px 12px #0002; --shadow-3: 0 8px 32px #0003;`;
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), `/* Generated by tools/generate-tokens.mjs. Material 3, seed #5266a4. */\n:root {\n  color-scheme: light;\n${scheme(false)}\n${aliases}\n}\n@media (prefers-color-scheme: dark) {\n:root {\n  color-scheme: dark;\n${scheme(true)}\n}\n}\n`);
